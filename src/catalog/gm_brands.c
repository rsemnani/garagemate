const GmBrand* gm_brands(void) {
    return brands;
}

size_t gm_brand_count(void) {
    return COUNT_OF(brands);
}

const GmBrand* gm_brand_at(size_t index) {
    if(index >= COUNT_OF(brands)) return NULL;
    return &brands[index];
}

const GmBrand* gm_brand_by_id(const char* id) {
    if(id == NULL) return NULL;
    for(size_t i = 0; i < COUNT_OF(brands); i++) {
        if(strcmp(brands[i].id, id) == 0) return &brands[i];
    }
    return NULL;
}

size_t gm_brand_index(const GmBrand* brand) {
    for(size_t i = 0; i < COUNT_OF(brands); i++) {
        if(&brands[i] == brand) return i;
    }
    return 0;
}

void gm_format_frequency(uint32_t frequency, char* out, size_t out_size) {
    furi_assert(out);
    // Frequencies are whole kHz in practice, so integer maths keeps this exact.
    uint32_t mhz = frequency / 1000000UL;
    uint32_t hundredths = (frequency % 1000000UL) / 10000UL;
    snprintf(out, out_size, "%lu.%02lu MHz", (unsigned long)mhz, (unsigned long)hundredths);
}
